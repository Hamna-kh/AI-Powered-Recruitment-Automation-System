-- ============================================================
-- AI Resume Shortlisting System - database setup (Supabase / PostgreSQL)
-- Tables: job, "Resume", talent_matches
-- Run this whole file once in the Supabase SQL Editor on an empty project.
-- ============================================================

-- pgvector is needed for the CV / JD embeddings (Gemini, 768 dimensions)
create extension if not exists vector;

-- ------------------------------------------------------------
-- 1. job : open positions created from the HR portal
-- ------------------------------------------------------------
create table if not exists job (
  id                    bigint generated by default as identity primary key,
  job_title             text not null,
  job_description       text,
  required_skills       text[],
  preferred_skills      text[],
  min_experience_years  numeric,
  scoring_logic         text,
  created_at            timestamptz default now(),
  department            text,
  location              text,
  status                text default 'open',          -- 'open' or 'closed'
  job_code              text unique,
  jd_embedding          vector(768),                  -- Gemini embedding of the job description
  talent_scanned_at     timestamptz                   -- null = talent-pool rematching not run yet
);

-- ------------------------------------------------------------
-- 2. "Resume" : every CV application, with its AI score and interview data
-- ------------------------------------------------------------
create table if not exists "Resume" (
  id                  bigint generated by default as identity primary key,
  created_at          timestamptz not null default now(),
  candidate_name      text,
  experience_yrs      numeric,
  tech_stack          json,
  match_score         integer,
  analysis_summary    text,
  job_id              smallint,                       -- refers to job.id
  candidate_email     text,
  job_title           text,
  status              text,                           -- Shortlisted / HR Review / Not Qualified / Rejected
  cv_url              text,                           -- file in the Supabase Storage bucket "cvs"
  interview_status    text,                           -- Scheduled / Cancelled ...
  interview_start     timestamptz,
  interview_event_id  text,                           -- Google Calendar event id
  interview_date      text,
  interview_end       timestamptz,
  interview_kit       text,                           -- AI interview kit (questions, gaps, red flags)
  cv_embedding        vector(768),                    -- Gemini embedding of the CV text
  cv_text             text,
  source              text                            -- 'talent_pool' for rematched candidates
);

-- ------------------------------------------------------------
-- 3. talent_matches : result of talent-pool rematching (one row per job + CV)
-- ------------------------------------------------------------
create table if not exists talent_matches (
  id               bigint generated by default as identity primary key,
  job_id           bigint not null,
  resume_id        bigint not null,
  candidate_name   text,
  candidate_email  text,
  previous_job     text,
  previous_status  text,
  similarity       double precision,
  new_score        integer,
  reason           text,
  created_at       timestamptz default now(),
  unique (job_id, resume_id)
);

-- ------------------------------------------------------------
-- 4. Function: copy a talent-pool match into the HR portal list ("Resume")
--    Called by the n8n node "Add to HR Portal".
-- ------------------------------------------------------------
create or replace function add_talent_match_to_portal(
  p_job_id text, p_resume_id text, p_score int, p_reason text
) returns void language plpgsql as $$
begin
  -- already applied to this job: refresh score and status, never touch decided candidates
  update "Resume" x
     set match_score = p_score,
         status = 'HR Review',
         analysis_summary = 'Re-evaluated after the job was reopened: ' || p_reason
    from "Resume" r
   where r.id::text = p_resume_id
     and x.job_id::text = p_job_id
     and lower(x.candidate_email) = lower(r.candidate_email)
     and x.status in ('HR Review', 'Not Qualified');

  -- not on this job yet: add as a new HR Review row
  insert into "Resume" (
    candidate_name, candidate_email, job_id, job_title, experience_yrs,
    tech_stack, match_score, status, analysis_summary, cv_url, cv_text, source
  )
  select r.candidate_name, r.candidate_email, j.id, j.job_title, r.experience_yrs,
         r.tech_stack, p_score, 'HR Review',
         'Talent pool match (previously ' || r.status || ' for ' || r.job_title || '): ' || p_reason,
         r.cv_url, r.cv_text, 'talent_pool'
  from "Resume" r, job j
  where r.id::text = p_resume_id
    and j.id::text = p_job_id
    and not exists (
      select 1 from "Resume" x
      where x.job_id = j.id and lower(x.candidate_email) = lower(r.candidate_email)
    );
end $$;

-- ------------------------------------------------------------
-- 5. Storage bucket for uploaded CVs
--    (public so the HR portal "View CV" link opens; make it private if you add signed URLs)
-- ------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('cvs', 'cvs', true)
on conflict (id) do nothing;

